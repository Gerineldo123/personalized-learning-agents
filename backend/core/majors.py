def flat_majors(discipline: str | None = None, keyword: str | None = None) -> list[str]:
    results = []
    for disc, categories in MAJORS_TREE.items():
        if discipline and disc != discipline:
            continue
        for cat in categories:
            for major in cat["majors"]:
                if keyword and keyword not in major:
                    continue
                results.append(major)
    return results


def get_tree(discipline: str | None = None) -> dict:
    if discipline and discipline in MAJORS_TREE:
        return {discipline: MAJORS_TREE[discipline]}
    return MAJORS_TREE


def flatten_all_majors() -> list[str]:
    return flat_majors()
